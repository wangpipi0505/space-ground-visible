async page => {
  const assert = (ok, message) => { if (!ok) throw Error(message) }
  const expectedMean=await page.locator('.ballistic-payload-view [data-satellite-id] [data-orbit-field=meanAnomalyDeg]').first().inputValue()
  await page.getByRole('tab', { name:'模拟弹道',exact:true }).click()
  const simulation = page.locator('.ballistic-simulation-view')
  await page.waitForTimeout(400)
  await page.screenshot({ path:'G:/5-YG/space-ground-visible/verification/A07/implementation/final-simulation-1440.png' })
  await simulation.getByText('高级设置 · JSON导入与编辑',{exact:true}).click()
  const draft = JSON.parse(await simulation.locator('[data-test=simulation-input]').inputValue())
  draft.compatibilityNote = { id:'90071992547409931',enabled:true }
  await simulation.locator('[data-test=simulation-input]').fill(JSON.stringify(draft))
  await simulation.locator('[data-simulation-field=impactPointUnit]').fill('meter')
  const pending = page.waitForResponse(r => r.url().endsWith('/api/trajectory/simulate'), {timeout:120000})
  await simulation.locator('[data-test=simulation-compute]').click()
  const response = await pending, request = response.request().postDataJSON(), raw = await response.text(), result = JSON.parse(raw)
  assert(response.status()===200 && result.files[0].pointCount===2576, '默认模拟点数/状态不符')
  assert(request.impactPointUnit==='meter' && request.compatibilityNote.id==='90071992547409931', '模拟末格/未知字段丢失')
  await simulation.locator('[data-test=fit-trajectory]').waitFor()
  for (const [selector,name] of [['[data-test=fit-download]','simulation.csv']]) {
    const download=page.waitForEvent('download'); await simulation.locator(selector).click(); await (await download).saveAs(`G:/5-YG/space-ground-visible/verification/runtime/A07/implementation/${name}`)
  }
  const simJson=page.waitForEvent('download'); await simulation.getByRole('button',{name:'下载结果 JSON',exact:true}).click(); await (await simJson).saveAs('G:/5-YG/space-ground-visible/verification/runtime/A07/implementation/simulation-response.json')
  await simulation.locator('[data-test=simulation-input]').evaluate(el => { el.closest('details').open=false })
  await page.waitForTimeout(400)
  await page.screenshot({path:'G:/5-YG/space-ground-visible/verification/A07/implementation/final-simulation-result.png'})
  page.__a07.runs.simulation={request,result,raw,status:response.status()}
  await page.getByRole('tab',{name:'弹道重定时',exact:true}).click()
  const retime=page.locator('.ballistic-retime-view')
  await retime.locator('[data-test=retime-source-mode]').selectOption('generated')
  const options=await retime.locator('[data-test=retime-result-select] option').evaluateAll(items=>items.map(i=>({value:i.value,text:i.textContent})))
  const source=options.find(item=>item.text.includes('模拟/defaultSimTask/SIM-001'))
  assert(source,'模拟引用未跨子页')
  await retime.locator('[data-test=retime-result-select]').selectOption(source.value)
  await retime.locator('[data-test=retime-source-reference]').waitFor()
  await page.waitForTimeout(400)
  await page.screenshot({path:'G:/5-YG/space-ground-visible/verification/A07/implementation/final-retime-1440.png'})
  const retimePending=page.waitForResponse(r=>r.url().endsWith('/api/trajectory/retime'),{timeout:120000})
  await retime.locator('[data-test=retime-compute]').click()
  const rr=await retimePending, retimeRequest=rr.request().postDataJSON(), retimeRaw=await rr.text(), retimeResult=JSON.parse(retimeRaw)
  assert(rr.status()===200 && retimeResult.files[0].pointCount===2576,'重定时未成功')
  await retime.locator('[data-test=fit-trajectory]').waitFor()
  const retimeCsv=page.waitForEvent('download'); await retime.locator('[data-test=fit-download]').click(); await (await retimeCsv).saveAs('G:/5-YG/space-ground-visible/verification/runtime/A07/implementation/retime.csv')
  const retimeJson=page.waitForEvent('download'); await retime.getByRole('button',{name:'下载结果 JSON',exact:true}).click(); await (await retimeJson).saveAs('G:/5-YG/space-ground-visible/verification/runtime/A07/implementation/retime-response.json')
  await page.waitForTimeout(400)
  await page.screenshot({path:'G:/5-YG/space-ground-visible/verification/A07/implementation/final-retime-result.png'})
  page.__a07.runs.retime={request:retimeRequest,result:retimeResult,raw:retimeRaw,status:rr.status()}
  await page.getByRole('tab',{name:'可视窗口计算',exact:true}).click()
  const window=page.locator('.ballistic-payload-view')
  assert(await window.locator('[data-satellite-id] [data-orbit-field=meanAnomalyDeg]').first().inputValue()===expectedMean,'切换丢失卫星草稿')
  await window.locator('[data-test=window-source]').selectOption('generated')
  const generated=await window.locator('[data-test=generated-result-select] option').evaluateAll(items=>items.map(i=>({value:i.value,text:i.textContent})))
  assert(generated.filter(i=>i.value).length===4,'生成引用未按fileId合并')
  const chosen=generated.find(i=>i.text.includes('重定时/retimeTrajectory/RET-001'))
  await window.locator('[data-test=generated-result-select]').selectOption(chosen.value)
  const reuseDownload=page.waitForEvent('download'); await window.getByRole('button',{name:'下载原始文件',exact:true}).click(); await (await reuseDownload).saveAs('G:/5-YG/space-ground-visible/verification/runtime/A07/implementation/retime-reused.csv')
  await window.locator('[data-option=numCalculations]').fill('1')
  const reusePending=page.waitForResponse(r=>r.url().endsWith('/api/orbit/visibility/search'),{timeout:120000})
  await window.locator('[data-test=compute-window]').click()
  const reused=await reusePending, reusedRequest=reused.request().postDataJSON()
  assert(reused.status()===200 && reusedRequest.ballistics[0].targetId==='RET-001' && !('baseLaunchUTC' in reusedRequest.ballistics[0]),'复用目标/UTC不符')
  page.__a07.reuse={status:reused.status(),request:reusedRequest,generatedCount:4}
  return {fit:page.__a07.runs.fit.status,simulation:response.status(),simulationPoints:result.files[0].pointCount,retime:rr.status(),retimePoints:retimeResult.files[0].pointCount,reuse:reused.status(),generatedCount:4}
}
