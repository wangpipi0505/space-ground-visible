/** Playwright CLI 双星真实配置/预览；使用已有页面快照中的表单、选项和动作，不设置 mock。 */
async (page) => {
  const assert = (condition, message) => { if (!condition) throw new Error(message) }
  const errors = []
  const requests = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  page.on('request', request => { if (request.url().endsWith('/payloads/preview')) requests.push(request.postDataJSON()) })
  // 浏览器 reload 后任务选择按原设计不持久化；先真实勾选空间星作为导航保留的起始条件。
  await page.getByRole('tab', { name: '规划工作台', exact: true }).click()
  await page.getByRole('row').filter({ hasText: '演示观测星（非生产资料）' }).locator('.el-checkbox__input').click()
  await page.locator('.payload-panel [data-field="minDistanceKm"] input').waitFor()
  await page.getByRole('tab', { name: '弹道载荷配置', exact: true }).click()
  const view = page.locator('.ballistic-payload-view')
  // ElementPlus 多选的透明输入被占位文字覆盖，按实际可点击选择框打开，不 force 点击内部输入。
  await view.locator('.el-select').first().click()
  await page.getByRole('option', { name: '演示观测星（非生产资料）', exact: true }).click()
  await page.getByRole('option', { name: 'T21合成观测星二号（非生产资料）', exact: true }).click()
  await page.keyboard.press('Escape')
  await view.locator('[data-test="add-ballistic-payload-1"]').click()
  await view.locator('[data-test="add-ballistic-payload-21"]').click()
  const star1 = view.locator('[data-satellite-id="1"]')
  const star2 = view.locator('[data-satellite-id="21"]')
  const payload1 = star1.locator('[data-payload-id]').nth(0)
  const payload2 = star1.locator('[data-payload-id]').nth(1)
  const payload3 = star2.locator('[data-payload-id]').nth(0)
  const payload4 = star2.locator('[data-payload-id]').nth(1)
  const fill = async (payload, name, value) => { const input = payload.locator(`[data-field="${name}"] input`); await input.fill(value); await input.press('Tab') }
  const selectGround = async payload => {
    const selector = payload.locator('[data-field="payloadType"] .el-select')
    await selector.click()
    const listId = await selector.getByRole('combobox').getAttribute('aria-controls')
    await page.locator(`#${listId}`).getByRole('option', { name: '对地载荷', exact: true }).click()
  }
  const identities = await view.locator('[data-payload-id]').evaluateAll(items => items.map(item => item.dataset.payloadId))
  assert(new Set(identities).size === 4, '双星载荷身份重复')
  await payload1.getByRole('textbox', { name: '载荷名称' }).fill('星甲对空独立配置')
  await fill(payload1, 'minDistanceKm', '111')
  await fill(payload1, 'maxDistanceKm', '0')
  await fill(payload1, 'angleRateDegPerSec', '-1')
  await fill(payload1, 'startupAngleRateDegPerSec', '-1')
  await fill(payload1, 'sunAvoidHalfAngleDeg', '0')
  for (const name of ['azimuthMinDeg', 'azimuthMaxDeg', 'elevationMinDeg', 'elevationMaxDeg']) await fill(payload1, name, '')
  await selectGround(payload2)
  await payload2.getByRole('textbox', { name: '载荷名称' }).fill('星甲对地独立配置')
  await fill(payload2, 'minDistanceKm', '333')
  await fill(payload2, 'elevationMinDeg', '-91')
  await fill(payload2, 'elevationMaxDeg', '90')
  await fill(payload2, 'angleRateDegPerSec', '0')
  await fill(payload2, 'startupAngleRateDegPerSec', '-1')
  await payload3.getByRole('textbox', { name: '载荷名称' }).fill('星乙对空独立配置')
  await fill(payload3, 'minDistanceKm', '222')
  await fill(payload3, 'angleRateDegPerSec', '0')
  await selectGround(payload4)
  await payload4.getByRole('textbox', { name: '载荷名称' }).fill('星乙对地独立配置')
  await fill(payload4, 'minDistanceKm', '444')
  await fill(payload4, 'elevationMinDeg', '-91')
  await fill(payload4, 'angleRateDegPerSec', '0')
  const evidence = []
  const preview = async payload => {
    const responsePromise = page.waitForResponse(response => response.url().endsWith('/api/v1/ballistic/payloads/preview') && response.request().method() === 'POST')
    await payload.getByRole('button', { name: '校验并预览' }).click()
    const response = await responsePromise
    const body = await response.json()
    const request = response.request().postDataJSON()
    evidence.push({ url: response.url(), method: 'POST', request, status: response.status(), response: body })
    assert(response.status() === 200 && Object.keys(body).length === 12, '真实预览未返回完整十二字段')
    assert(JSON.stringify(body) === JSON.stringify(request), '服务未按标准字段原值回显')
    await payload.getByText('服务已校验，完整配置回显').waitFor()
    return body
  }
  const response1 = await preview(payload1)
  const response2 = await preview(payload2)
  const response3 = await preview(payload3)
  const response4 = await preview(payload4)
  assert(response1.minDistanceKm === 111 && response1.angleRateDegPerSec === -1 && response1.azimuthMinDeg === null && response1.elevationMaxDeg === null, 'SPACE空值负一改变')
  assert(response2.payloadType === 'GROUND' && response2.angleRateDegPerSec === 0 && response2.elevationMinDeg === -91, 'GROUND边界改变')
  assert(response3.minDistanceKm === 222 && response4.minDistanceKm === 444, '另一颗星配置串扰')
  await star1.screenshot({ path: 'G:/5-YG/space-ground-visible/output/playwright/T21/ballistic-star1-previews.png' })
  await star2.screenshot({ path: 'G:/5-YG/space-ground-visible/output/playwright/T21/ballistic-star2-previews.png' })
  const beforeInvalid = requests.length
  await fill(payload2, 'azimuthMinDeg', '')
  assert(await payload2.getByRole('button', { name: '校验并预览' }).isDisabled(), '单null未阻止预览')
  assert((await payload2.innerText()).includes('方位角上下限必须同时填写或同时留空'), '非法姿态缺中文错误')
  await fill(payload2, 'azimuthMaxDeg', '')
  await fill(payload2, 'angleRateDegPerSec', '-1')
  assert(await payload2.getByRole('button', { name: '校验并预览' }).isDisabled(), '对地-1未阻止预览')
  assert((await payload2.innerText()).includes('不能使用 -1'), 'GROUND非法缺中文错误')
  assert(requests.length === beforeInvalid, '非法表单产生请求')
  await payload2.screenshot({ path: 'G:/5-YG/space-ground-visible/output/playwright/T21/ballistic-invalid-blocked.png' })
  await fill(payload2, 'angleRateDegPerSec', '0')
  await preview(payload2)
  const otherStarIds = await star2.locator('[data-payload-id]').evaluateAll(items => items.map(item => item.dataset.payloadId))
  const deletedId = await payload2.getAttribute('data-payload-id')
  await payload2.getByRole('button', { name: '删除载荷' }).click()
  assert(await star1.locator('[data-payload-id]').count() === 1 && await star2.locator('[data-payload-id]').count() === 2, '删除串另一颗星')
  assert(JSON.stringify(await star2.locator('[data-payload-id]').evaluateAll(items => items.map(item => item.dataset.payloadId))) === JSON.stringify(otherStarIds), '删除改变另一星身份/顺序')
  await star1.getByRole('button', { name: '新增载荷' }).click()
  const afterDeleteIds = await view.locator('[data-payload-id]').evaluateAll(items => items.map(item => item.dataset.payloadId))
  assert(new Set(afterDeleteIds).size === 4 && !afterDeleteIds.includes(deletedId), '新增重复使用删除身份')
  await page.getByRole('tab', { name: '规划工作台', exact: true }).click()
  assert(await page.locator('.payload-panel [data-field="minDistanceKm"] input').inputValue() === '321', '导航重置空间profile草稿')
  await page.getByRole('tab', { name: '弹道载荷配置', exact: true }).click()
  assert(JSON.stringify(await view.locator('[data-payload-id]').evaluateAll(items => items.map(item => item.dataset.payloadId))) === JSON.stringify(afterDeleteIds), '导航重置弹道多载荷草稿')
  const invalidRequest = { ...response2, angleRateDegPerSec: -1 }
  const invalidResponse = await page.request.post('http://127.0.0.1:15121/api/v1/ballistic/payloads/preview', { data: invalidRequest })
  const invalidBody = await invalidResponse.json()
  assert(invalidResponse.status() === 400 && invalidBody.code === 'INVALID_ARGUMENT', '服务非法标准未400')
  evidence.push({ source: '真实独立HTTP负例；表单非法已阻止HTTP', url: invalidResponse.url(), method: 'POST', request: invalidRequest, status: invalidResponse.status(), response: invalidBody })
  assert(errors.length === 0, '页面控制台错误')
  return { browser: 'Chrome headless', timezone: await page.evaluate(() => Intl.DateTimeFormat().resolvedOptions().timeZone), identities, afterDeleteIds, checks: ['双星各两载荷真实编辑', 'SPACE/GROUND完整预览与原值', '清空双null', '中文非法阻止HTTP', '多载荷增删与身份隔离', '导航保留两业务状态', '后端真实400'], evidence, pagePreviewRequests: requests.length, consoleErrors: errors }
}
