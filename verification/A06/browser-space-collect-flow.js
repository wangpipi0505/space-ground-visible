  await workbench.screenshot({path:'G:/5-YG/space-ground-visible/verification/A06/space-workbench.png'})
  await page.getByRole('tab',{name:'任务结果记录',exact:true}).click()
  const history=page.locator('[data-test=task-result-records]')
  await history.waitFor()
  const records=page.waitForResponse(r=>r.url().includes('/task-results')&&r.request().method()==='GET')
  await history.locator('[data-test=query-task-results]').click();assert((await records).status()===200,'任务记录不能查询')
