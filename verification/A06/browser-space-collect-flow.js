  const assert=(ok,text)=>{if(!ok)throw new Error(text)}
  await page.getByRole('tab',{name:'规划工作台',exact:true}).click()
  const workbench=page.locator('.planning-workbench')
  assert(await workbench.locator('[data-test=satellite-station-selection]').isVisible()&&await workbench.locator('[data-test=satellite-station-links]').isVisible()&&await workbench.locator('[data-test=target-visibility-planning]').isVisible(),'空间三列正文不在原父页')
