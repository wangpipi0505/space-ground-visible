-- =====================================================================
-- 空间目标可见窗口服务 —— 达梦数据库（DM8）建库脚本
--
-- 与 db/mysql/schema.sql 及 MySQL 侧 Flyway 迁移 V1~V7 合并后的最终表结构等价，供使用达梦数据库的
-- 集成方环境一次性执行（DM 管理工具或 disql）。达梦侧不启用 Flyway
-- （spring.flyway.enabled=false），结构变更由本脚本维护。
--
-- 与 MySQL 版的差异说明：
--   1. 自增主键使用 DM 原生 IDENTITY(1,1)（应用层实际使用雪花 ID，不依赖自增）；
--   2. PAYLOAD_JSON_ 由 MySQL JSON 类型改为 CLOB（DM8 无独立 JSON 类型，
--      应用层按字符串读写，行为一致）；
--   3. 日期时间使用 TIMESTAMP(3)，等价于 MySQL DATETIME(3)；
--   4. V2 迁移（NAME_ 唯一约束替换为 SCID_ 唯一索引）已直接体现在最终结构中。
--
-- 建议在独立表空间/用户下执行，例如：
--   CREATE USER SPACE_TARGET_VISIBLE IDENTIFIED BY "<口令>";
--   GRANT RESOURCE TO SPACE_TARGET_VISIBLE;
-- 然后以该用户连接执行本脚本。
-- =====================================================================

-- 地面站表
CREATE TABLE ZG_STATION (
    ID_ VARCHAR(64) NOT NULL,
    NAME_ VARCHAR(255) NOT NULL,
    LONGITUDE_ DECIMAL(10, 6),
    LATITUDE_ DECIMAL(10, 6),
    HEIGHT_ DECIMAL(10, 2),
    MIN_ELEVATION_ DECIMAL(10, 2),
    MAX_ELEVATION_ DECIMAL(10, 2),
    CREATE_BY_ VARCHAR(64),
    CREATE_ORG_ID_ VARCHAR(64),
    CREATE_TIME_ TIMESTAMP(3),
    UPDATE_BY_ VARCHAR(64),
    UPDATE_TIME_ TIMESTAMP(3),
    PRIMARY KEY (ID_)
);

-- 我方卫星表
CREATE TABLE ZG_XZ_MANAGE (
    ID_ BIGINT IDENTITY(1, 1) NOT NULL,
    TYPE_ VARCHAR(255),
    LIBRARY_MODEL_ID_ BIGINT,
    NAME_ VARCHAR(255) NOT NULL,
    SCID_ BIGINT,
    MODEL_TYPE_ VARCHAR(32) NOT NULL,
    EPOCH_TIME_ TIMESTAMP(3),
    A_ DECIMAL(22, 6),
    E_ DECIMAL(22, 12),
    I_ DECIMAL(22, 6),
    M_ DECIMAL(22, 6),
    RAAN_ DECIMAL(22, 6),
    ARG_PER_ DECIMAL(22, 6),
    PAYLOAD_JSON_ CLOB,
    FIRST_ORBIT_ VARCHAR(255),
    SECOND_ORBIT_ VARCHAR(255),
    CREATED_BY_ VARCHAR(64),
    UPDATE_BY_ VARCHAR(64),
    CREATE_TIME_ TIMESTAMP(3),
    UPDATE_TIME_ TIMESTAMP(3),
    OBJECT_ID_ VARCHAR(64),
    OBJECT_NAME_ VARCHAR(255),
    NORAD_CAT_ID_ BIGINT,
    COUNTRY_ VARCHAR(50),
    PERIOD_ DECIMAL(12, 6),
    INCLINATION_ DECIMAL(12, 6),
    APOGEE_ DECIMAL(12, 3),
    PERIGEE_ DECIMAL(12, 3),
    RCS_SIZE_ VARCHAR(50),
    RCSVALUE_ DECIMAL(22, 6),
    LAUNCH_ DATE,
    COMMENT_ VARCHAR(255),
    WEIGHT_ DECIMAL(22, 6),
    PRIMARY KEY (ID_)
);

CREATE UNIQUE INDEX UK_ZG_XZ_MANAGE_SCID ON ZG_XZ_MANAGE (SCID_);

