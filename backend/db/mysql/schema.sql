-- =====================================================================
-- 空间目标可见窗口服务 —— MySQL 最终建表脚本
--
-- 本脚本合并 Flyway V1～V7 的最终结构，适用于集成方首次部署或
-- 需要一次性创建完整数据库结构的场景。已存在的数据库由 Flyway
-- 按迁移版本管理，不应重复执行本脚本覆盖现有表。
-- =====================================================================

CREATE TABLE ZG_STATION (
    ID_ VARCHAR(64) NOT NULL,
    NAME_ VARCHAR(255) NOT NULL,
    LONGITUDE_ DECIMAL(10, 6),
    LATITUDE_ DECIMAL(10, 6),
    HEIGHT_ DECIMAL(10, 2),
    MIN_ELEVATION_ DECIMAL(10, 2),
    MAX_ELEVATION_ DECIMAL(10, 2),
    CREATE_BY_ VARCHAR(64),
    CREATE_ORG_ID_ VARCHAR(64),
    CREATE_TIME_ DATETIME(3),
    UPDATE_BY_ VARCHAR(64),
    UPDATE_TIME_ DATETIME(3),
    PRIMARY KEY (ID_)
);

CREATE TABLE ZG_XZ_MANAGE (
    ID_ BIGINT NOT NULL AUTO_INCREMENT,
    TYPE_ VARCHAR(255),
    LIBRARY_MODEL_ID_ BIGINT,
    NAME_ VARCHAR(255) NOT NULL,
    SCID_ BIGINT,
    MODEL_TYPE_ VARCHAR(32) NOT NULL,
    EPOCH_TIME_ DATETIME(3),
    A_ DECIMAL(22, 6),
    E_ DECIMAL(22, 12),
    I_ DECIMAL(22, 6),
    M_ DECIMAL(22, 6),
    RAAN_ DECIMAL(22, 6),
    ARG_PER_ DECIMAL(22, 6),
    PAYLOAD_JSON_ JSON,
    FIRST_ORBIT_ VARCHAR(255),
    SECOND_ORBIT_ VARCHAR(255),
    CREATED_BY_ VARCHAR(64),
    UPDATE_BY_ VARCHAR(64),
    CREATE_TIME_ DATETIME(3),
    UPDATE_TIME_ DATETIME(3),
    OBJECT_ID_ VARCHAR(64),
    OBJECT_NAME_ VARCHAR(255),
    NORAD_CAT_ID_ BIGINT,
    COUNTRY_ VARCHAR(50),
    PERIOD_ DECIMAL(12, 6),
    INCLINATION_ DECIMAL(12, 6),
    APOGEE_ DECIMAL(12, 3),
    PERIGEE_ DECIMAL(12, 3),
    RCS_SIZE_ VARCHAR(50),
    RCSVALUE_ DECIMAL(22, 6),
    LAUNCH_ DATE,
    COMMENT_ VARCHAR(255),
    WEIGHT_ DECIMAL(22, 6),
    PRIMARY KEY (ID_)
);

CREATE UNIQUE INDEX UK_ZG_XZ_MANAGE_SCID ON ZG_XZ_MANAGE (SCID_);

CREATE TABLE ZG_XZ_MANAGE_TARGET (
    ID_ BIGINT NOT NULL AUTO_INCREMENT,
    TYPE_ VARCHAR(255),
    LIBRARY_MODEL_ID_ BIGINT,
    NAME_ VARCHAR(255) NOT NULL,
    SCID_ BIGINT,
    MODEL_TYPE_ VARCHAR(32) NOT NULL,
    EPOCH_TIME_ DATETIME(3),
    A_ DECIMAL(22, 6),
    E_ DECIMAL(22, 12),
    I_ DECIMAL(22, 6),
    M_ DECIMAL(22, 6),
    RAAN_ DECIMAL(22, 6),
    ARG_PER_ DECIMAL(22, 6),
    FIRST_ORBIT_ VARCHAR(255),
    SECOND_ORBIT_ VARCHAR(255),
    BELONG_ VARCHAR(50),
    WEIGHT_ DECIMAL(22, 6),
    CREATE_BY_ VARCHAR(64),
    UPDATE_BY_ VARCHAR(64),
    CREATE_ORG_ID_ VARCHAR(64),
    CREATE_TIME_ DATETIME(3),
    UPDATE_TIME_ DATETIME(3),
    OBJECT_ID_ VARCHAR(64),
    OBJECT_NAME_ VARCHAR(255),
    NORAD_CAT_ID_ BIGINT,
    COUNTRY_ VARCHAR(50),
    PERIOD_ DECIMAL(12, 6),
    INCLINATION_ DECIMAL(12, 6),
    APOGEE_ DECIMAL(12, 3),
    PERIGEE_ DECIMAL(12, 3),
    RCS_SIZE_ VARCHAR(50),
    RCSVALUE_ DECIMAL(22, 6),
    LAUNCH_ DATE,
    COMMENT_ VARCHAR(255),
    PRIMARY KEY (ID_)
);

CREATE UNIQUE INDEX UK_ZG_XZ_MANAGE_TARGET_SCID ON ZG_XZ_MANAGE_TARGET (SCID_);
CREATE INDEX IDX_ZG_XZ_TARGET_BELONG ON ZG_XZ_MANAGE_TARGET (BELONG_);
CREATE INDEX IDX_ZG_XZ_TARGET_WEIGHT ON ZG_XZ_MANAGE_TARGET (WEIGHT_);
CREATE INDEX IDX_ZG_XZ_TARGET_EPOCH ON ZG_XZ_MANAGE_TARGET (EPOCH_TIME_);

CREATE TABLE ZG_VISIBILITY_TASK_RESULT (
    ID_ BIGINT NOT NULL AUTO_INCREMENT,
    TASK_ID_ VARCHAR(64) NOT NULL,
    TASK_TYPE_ VARCHAR(32) NOT NULL,
    STATUS_ VARCHAR(16) NOT NULL,
    TOTAL_PAIRS_ BIGINT,
    COMPLETED_PAIRS_ BIGINT,
    ERROR_MESSAGE_ VARCHAR(1024),
    REQUEST_JSON_ LONGTEXT,
    RESULT_JSON_ LONGTEXT,
    SKIPPED_PAIRS_ LONGTEXT,
    REMARK_ VARCHAR(512),
    SELECTION_JSON_ LONGTEXT NULL,
    CREATE_TIME_ DATETIME(3),
    COMPLETE_TIME_ DATETIME(3),
    PRIMARY KEY (ID_)
);

CREATE UNIQUE INDEX UK_ZG_VIS_TASK_RESULT_TASK ON ZG_VISIBILITY_TASK_RESULT (TASK_ID_);
CREATE INDEX IDX_ZG_VIS_TASK_RESULT_STATUS ON ZG_VISIBILITY_TASK_RESULT (STATUS_);
CREATE INDEX IDX_ZG_VIS_TASK_RESULT_CREATE_TIME ON ZG_VISIBILITY_TASK_RESULT (CREATE_TIME_);
